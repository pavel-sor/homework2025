// Задача 1.
// Напишите цикл, который выводит числа от 1 до 20, но пропускает те числа,
// которые делятся на 4 без остатка.

//Решение:
for (let i = 1; i <= 20; i++) {
  if (i % 4 !== 0) {
    alert(i);
  }
}

// Задача 2.
// С помощью цикла for вычислите факториал числа (произведение всех чисел
// от 1 до заданного числа). Используйте prompt для получение начального значения.

//Решение:
let number = prompt("Введите число для вычисления факториала:");
number = parseInt(number);

if (isNaN(number) || number < 0) {
  alert("Пожалуйста, введите неотрицательное целое число!");
} else {
  let factorial = 1;

  if (number === 0 || number === 1) {
    alert(number + "! = 1");
  } else {
    let calculation = "1";

    for (let i = 1; i <= number; i++) {
      factorial *= i;
      if (i > 1) {
        calculation += " × " + i;
      }
    }

    alert(number + "! = " + calculation + " = " + factorial);
  }
}

// *Задача 3.
// Выведите в консоль шахматную доску размером 8x8, где символы чередуются
// (например, # и пробел). Начинайте с # в первой ячейке первой строки.

//Решение:
let board = "";
for (let i = 0; i < 8; i++) {
  for (let j = 0; j < 8; j++) {
    board += (i + j) % 2 ? " " : "#";
  }
  board += "\n";
}
console.log(board);
