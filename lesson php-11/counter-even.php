<?php
// Создаем произвольный массив чисел
$numbers = [1, 5, 8, 12, 15, 20, 23, 26, 30, 33, 36, 40, 42, 47, 50];

echo "<h3>Исходный массив чисел:</h3>";
echo "<p>" . implode(", ", $numbers) . "</p>";

echo "<h3>Четные числа из массива:</h3>";

// Используем цикл for для обхода массива
for ($i = 0; $i < count($numbers); $i++) {
    // Проверяем, является ли число четным
    if ($numbers[$i] % 2 == 0) {
        echo $numbers[$i] . " - четное число<br>";
    }
}
?>